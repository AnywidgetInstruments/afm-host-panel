// Vendor the anywidget-instruments-automotive front end into
// src/widgets/anywidget-instruments-automotive/.
//
// As for anywidget-instruments (scripts/vendor-instruments.mjs), the built
// module and its CSS are copied byte for byte, as string modules: the plugin
// imports them lazily and loads the module through a blob: URL, as anywidget
// hosts load `_esm` text, so webpack never transforms the code. The module
// bundles the parts of anywidget-instruments it derives from, and its CSS
// includes the base styles: it does not depend on the other vendored copy.
//
// Usage: node scripts/vendor-automotive.mjs [path to an anywidget-instruments-automotive checkout]
// The checkout must be built first (`npm install && npm run build` there).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const from = resolve(process.argv[2] ?? '../anywidget-instruments-automotive');
const out = resolve('src/widgets/anywidget-instruments-automotive');
const staticDir = join(from, 'src/anywidget_instruments_automotive/static');

for (const f of ['index.js', 'index.css', 'contract.json']) {
  if (!existsSync(join(staticDir, f))) {
    console.error(`Missing ${join(staticDir, f)}: run "npm install && npm run build" in ${from} first.`);
    process.exit(1);
  }
}

const git = (...args) => execFileSync('git', ['-C', from, ...args], { encoding: 'utf8' }).trim();
const commit = git('rev-parse', 'HEAD');
const dirty = git('status', '--porcelain', '--untracked-files=no') !== '';
const contract = JSON.parse(readFileSync(join(staticDir, 'contract.json'), 'utf8'));

const kinds = Object.fromEntries(
  Object.entries(contract.widgets)
    .filter(([, spec]) => !spec.abstract && spec.kind)
    .map(([cls, spec]) => [cls, spec.kind])
    .sort(([a], [b]) => a.localeCompare(b))
);

const header = (what) =>
  `// Generated by scripts/vendor-automotive.mjs from anywidget-instruments-automotive ${commit}: ${what}. Do not edit.\n`;

mkdirSync(out, { recursive: true });
writeFileSync(
  join(out, 'esm.ts'),
  header('front-end module (static/index.js), unmodified') +
    `const esm: string = ${JSON.stringify(readFileSync(join(staticDir, 'index.js'), 'utf8'))};\nexport default esm;\n`
);
writeFileSync(
  join(out, 'css.ts'),
  header('styles (static/index.css), unmodified') +
    `const css: string = ${JSON.stringify(readFileSync(join(staticDir, 'index.css'), 'utf8'))};\nexport default css;\n`
);
writeFileSync(
  join(out, 'kinds.ts'),
  header('widget classes and their _kind, from static/contract.json') +
    `export const AUTOMOTIVE_KINDS: Record<string, string> = ${JSON.stringify(kinds, null, 2)};\n`
);
writeFileSync(join(out, 'LICENSE'), readFileSync(join(from, 'LICENSE')));
writeFileSync(
  join(out, 'SOURCE.json'),
  JSON.stringify(
    {
      repository: 'https://github.com/AnywidgetInstruments/anywidget-instruments-automotive',
      commit,
      contractFormat: contract.format,
      contractVersion: contract.version,
      dirtyWorkingTree: dirty,
      license: 'BSD-3-Clause',
    },
    null,
    2
  ) + '\n'
);
console.log(
  `Vendored anywidget-instruments-automotive ${commit}${dirty ? ' (working tree has local changes)' : ''}: ${Object.keys(kinds).length} widgets.`
);
